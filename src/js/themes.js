export function getTheme(id, extra = []) {
  return [...THEMES, ...COMMUNITY_THEMES, ...extra].find((theme) => theme.id === id) || THEMES[0];
}

export function applyTheme(theme, options = {}) {
  const root = document.documentElement;
  const vars = theme.vars;
  const map = {
    '--bg-0': vars.bg0,
    '--bg-1': vars.bg1,
    '--bg-2': vars.bg2,
    '--surface': vars.surface,
    '--surface-strong': vars.surfaceStrong,
    '--surface-soft': vars.surfaceSoft,
    '--surface-hover': vars.surfaceHover,
    '--stroke': vars.stroke,
    '--stroke-strong': vars.strokeStrong,
    '--text': vars.text,
    '--text-soft': vars.textSoft,
    '--muted': vars.muted,
    '--muted-strong': vars.mutedStrong,
    '--accent': vars.accent,
    '--accent-soft': vars.accentSoft,
    '--accent-deep': vars.accentDeep,
    '--accent-contrast': vars.accentContrast,
    '--accent-2': vars.accent2,
    '--accent-2-soft': vars.accent2Soft,
    '--accent-3': vars.accent3,
    '--success': vars.success,
    '--danger': vars.danger,
    '--warn': vars.warn,
    '--gradient-hero': vars.gradientHero,
    '--gradient-accent': vars.gradientAccent,
    '--gradient-sapphire': vars.gradientSapphire,
    '--orb-a': vars.orbA,
    '--orb-b': vars.orbB,
    '--orb-c': vars.orbC,
    '--glow': vars.glow,
    '--selection': vars.selection,
    '--scrollbar': vars.scrollbar,
    '--radius': `${options.cornerRadius ?? 22}px`
  };
  for (const [key, value] of Object.entries(map)) root.style.setProperty(key, value);
  root.dataset.theme = theme.id;
  root.dataset.rainbow = theme.special === 'rainbow' ? 'true' : 'false';
  root.dataset.reduceMotion = options.reduceMotion ? 'true' : 'false';
  root.dataset.acrylic = options.acrylic === false ? 'false' : 'true';
  root.dataset.density = options.density || 'comfortable';
}

